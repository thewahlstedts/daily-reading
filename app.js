// ---------- Group weeks ----------

// With a meeting day set, the goal is weekly: a week runs from the day after
// one meeting through the next meeting day. Only readings from before the
// current week count as behind.
let weekOffset = 0;   // 0 = current week; -1 = last week, etc.

function weekWindow(offset = 0) {
  if (state.meetDay == null) return null;
  const now = new Date();
  const toMeet = (state.meetDay - now.getDay() + 7) % 7;
  const end = new Date(now.getFullYear(), now.getMonth(), now.getDate() + toMeet + offset * 7);
  const endIdx = dayNumber(isoDate(end)) - dayNumber(state.start);
  return { startIdx: endIdx - 6, endIdx, meet: end, daysToMeet: toMeet + offset * 7 };
}

// The plan is 52 weeks of 7 readings. "Week N" is the same 7 readings for every
// group; only the calendar days differ, so weekly material can be keyed to it.
const planWeek = (i) => Math.floor(i / 7) + 1;

// A start on the day after the meeting day makes each group week exactly one plan week.
function isAligned(start = state.start, meetDay = state.meetDay) {
  return meetDay == null || localDate(start).getDay() === (meetDay + 1) % 7;
}

// The aligned start nearest to `start` (at most 3 days earlier or later).
function nearestAligned(start, meetDay) {
  const ahead = ((meetDay + 1) % 7 - localDate(start).getDay() + 7) % 7;
  return isoDate(localDate(start, ahead > 3 ? ahead - 7 : ahead));
}

function weekLabel(from, to) {
  const a = planWeek(from), b = planWeek(to);
  return a === b ? `Week ${a}` : `Weeks ${a}–${b}`;
}

// Today is meeting day and the meeting card hasn't been closed.
function meetingToday() {
  const w = weekWindow(0);
  return w?.daysToMeet === 0 && state.metOn !== isoDate(new Date()) ? w : null;
}

// Index before which unread readings count as behind.
function dueBefore() {
  const w = weekWindow(0);
  return w ? w.startIdx : todayIndex();
}

const fmtDay = new Intl.DateTimeFormat(undefined, { weekday: 'short', month: 'short', day: 'numeric' });
const fmtRange = new Intl.DateTimeFormat(undefined, { month: 'short', day: 'numeric' });

function renderWeek(t) {
  const w = weekWindow(weekOffset);
  $('#week').hidden = !w;
  if (!w) return null;
  const idxs = [];
  for (let i = Math.max(0, w.startIdx); i <= Math.min(plan.length - 1, w.endIdx); i++) idxs.push(i);
  const done = idxs.filter(isRead).length;

  // The plan week goes in the title; further out, it replaces "Week of …" since the dates are in the meta line.
  const near = ['Last week', 'This week', 'Next week'][weekOffset + 1];
  const planLabel = idxs.length ? weekLabel(idxs[0], idxs[idxs.length - 1]) : '';
  $('#week-title').textContent = near && planLabel ? `${near} · ${planLabel}`
    : near || planLabel || `Week of ${fmtShort.format(dateForIndex(w.startIdx))}`;
  $('#week-today').hidden = weekOffset === 0;
  // Short range ("Oct 15 – 21"): the list already shows each day, and the line should fit a phone.
  const range = fmtRange.formatRange(dateForIndex(w.startIdx), w.meet);
  let when;
  if (w.daysToMeet === 0) when = meetingToday() ? 'Meeting today' : 'Met today';
  else if (w.daysToMeet === 1) when = 'Meeting tomorrow';
  else if (w.daysToMeet > 1) when = `Meeting in ${w.daysToMeet} days`;
  else when = `Met ${fmtDay.format(w.meet)}`;
  // Each part stays whole (white-space: nowrap) so a narrow screen breaks only at the dots.
  $('#week-meta').innerHTML = (idxs.length
    ? [range, `<strong>${done} of ${idxs.length} read</strong>`, when]
    : [range, 'Outside the plan']).map((x) => `<span>${x}</span>`).join(' · ');
  $('#week-fill').style.width = idxs.length ? `${(done / idxs.length) * 100}%` : '0';
  $('#week-list').innerHTML = idxs.map((i) => itemHtml(i, t, dueBefore())).join('');
  setReviewButton($('#review-btn'), w);
  // On meeting day both buttons move up to the meeting card; when this week's
  // summary is in the today card (nothing read yet), it isn't repeated here.
  const meeting = weekOffset === 0 && Boolean(meetingToday());
  $('#review-btn').hidden = meeting;
  const n = summaryWeek(w);
  setSummaryButton($('#summary-btn'), meeting || n === summaryInCard ? null : n);
  return weekWindow(0);
}

// The plan week holding most of a group week's readings.
function summaryWeek(w) {
  const mid = Math.min(Math.max(w.startIdx + 3, 0), plan.length - 1);
  return mid >= w.startIdx && mid <= w.endIdx ? planWeek(mid) : null;
}

function setReviewButton(btn, w) {
  const marked = marksIn(w.startIdx, w.endIdx).length;
  btn.textContent = marked ? `Verses to discuss (${marked})` : 'No verses to discuss yet';
  btn.disabled = !marked;
}

// The group week holding reading i (same shape as weekWindow()).
function groupWeekOf(i) {
  const endIdx = i + (state.meetDay - dateForIndex(i).getDay() + 7) % 7;
  return { startIdx: endIdx - 6, endIdx };
}

// The summary to offer with reading i: its week's, while none of that week is read yet.
function startingSummary(i) {
  if (state.meetDay == null) {
    for (let j = i - i % 7; j < i - i % 7 + 7; j++) if (isRead(j)) return null;
    return planWeek(i);
  }
  if (meetingToday()) return null;   // the meeting card has the summary
  const w = groupWeekOf(i);
  for (let j = Math.max(w.startIdx, 0); j <= w.endIdx; j++) if (isRead(j)) return null;
  return summaryWeek(w);
}

// Meeting day: the week's verses to discuss and summary, up top. Once the
// week is read, the meeting is what's next, so it goes above the next reading
// (next week's, which only makes sense after the meeting).
function renderMeeting() {
  const w = meetingToday();
  const n = w ? summaryWeek(w) : null;   // null outside the plan
  const card = $('#meeting-card');
  card.hidden = n == null;
  if (n == null) return;
  let weekRead = true;
  for (let i = Math.max(w.startIdx, 0); i <= Math.min(w.endIdx, plan.length - 1); i++) if (!isRead(i)) weekRead = false;
  if (weekRead) $('#today-card').before(card);
  else $('#today-card').after(card);
  $('#meeting-title').textContent = weekLabel(Math.max(w.startIdx, 0), Math.min(w.endIdx, plan.length - 1));
  setReviewButton($('#meeting-review-btn'), w);
  setSummaryButton($('#meeting-summary-btn'), n);
}


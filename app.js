// Dragging a sheet to the right closes it, like its back button. The sheet follows
// the finger so the gesture can be abandoned by dragging back.
function swipeToClose(sheet, close) {
  let swipe = null;

  const settle = (closing) => {
    const done = () => {
      sheet.style.transition = '';
      sheet.style.transform = '';
      if (closing) close();
    };
    if (matchMedia('(prefers-reduced-motion: reduce)').matches) { done(); return; }
    sheet.style.transition = 'transform .2s ease-out';
    sheet.style.transform = closing ? 'translateX(100%)' : '';
    setTimeout(done, 200);
  };

  sheet.addEventListener('touchstart', (e) => {
    // A slider is dragged sideways too, so a drag that starts on one adjusts it instead.
    swipe = e.touches.length === 1 && !getSelection().toString() && !e.target.closest('input[type="range"]')
      ? { x: e.touches[0].clientX, y: e.touches[0].clientY, t: e.timeStamp, dx: 0, on: false }
      : null;
  }, { passive: true });

  sheet.addEventListener('touchmove', (e) => {
    if (!swipe) return;
    const dx = e.touches[0].clientX - swipe.x;
    const dy = e.touches[0].clientY - swipe.y;
    if (!swipe.on) {
      if (Math.abs(dx) < 10 && Math.abs(dy) < 10) return;
      // Decide once: a clearly rightward drag swipes; anything else scrolls as usual.
      if (e.touches.length > 1 || !e.cancelable || dx < Math.abs(dy) * 2) { swipe = null; return; }
      swipe.on = true;
      sheet.style.transition = 'none';
    }
    e.preventDefault();
    swipe.dx = Math.max(0, dx);
    sheet.style.transform = `translateX(${swipe.dx}px)`;
  }, { passive: false });

  sheet.addEventListener('touchend', (e) => {
    if (!swipe?.on) { swipe = null; return; }
    const { dx, t } = swipe;
    swipe = null;
    const fast = dx > 40 && dx / (e.timeStamp - t) > 0.5;
    settle(dx > sheet.clientWidth * 0.3 || fast);
  });

  sheet.addEventListener('touchcancel', () => {
    if (swipe?.on) settle(false);
    swipe = null;
  });
}


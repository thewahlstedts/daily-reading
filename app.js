function pickVoice() {
  if (!voices.length) return null;
  const saved = voices.find((v) => v.voiceURI === state.voice);
  if (saved) return saved;
  const score = (v) =>
    (/premium|enhanced|natural|neural/i.test(v.name) ? 4 : 0) +
    (v.lang === 'en-US' ? 2 : 0) +
    (v.localService ? 1 : 0) +
    (v.default ? 1 : 0);
  return [...voices].sort((a, b) => score(b) - score(a))[0];
}

